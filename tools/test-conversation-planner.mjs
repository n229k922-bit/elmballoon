import assert from 'node:assert/strict';
import { extractConversationFacts, planConversation } from '../workers/admin-line-secretary/src/conversation.js';

const sourceTimestamp = '2026-09-30T15:30:00Z'; // October 1 in the shop's timezone.
const extract = text => extractConversationFacts({ text, sourceTimestamp });
const field = (result, key) => result.updates.find(update => update.key === key)?.value;
let result = extract('予算は20,000〜30,000円で、スタンドをお願いします');
assert.equal(result.facts.budget.min, 20000);
assert.equal(result.facts.budget.max, 30000);
assert.equal(result.facts.budget.scope, 'unknown');
result = extract('合計2〜3万円で3つお願いします');
assert.equal(result.facts.budget.min, 20000);
assert.equal(result.facts.budget.max, 30000);
assert.equal(result.facts.budget.scope, 'total');
assert.equal(field(result, 'quantity'), '3');
assert.equal(extract('1つ800円で3つ').facts.budget.scope, 'unit');
assert.equal(field(extract('去年と同じ数字12でお願いします'), 'product_source'), undefined);
assert.equal(field(extract('商品番号: B36'), 'product_source'), 'B36');
assert.equal(field(extract('明日取りに行きます'), 'receive_date'), '2026-10-02');
assert.equal(field(extract('10月10日に受け取りたい'), 'receive_date'), '2026-10-10');
assert.equal(extract('2月30日に受け取りたい').facts.dateAmbiguities.length, 1);
assert.equal(extract('1月10日に受け取りたい').facts.dateAmbiguities.length, 1);
assert.equal(extractConversationFacts({ text: '明日取りに行く' }).facts.dateAmbiguities.length, 1);
result = extract('背番号1 RINO\n背番号4 YUUNA\n背番号5 RION');
assert.equal(result.facts.items.length, 3);
assert.equal(field(result, 'customer_name'), undefined);
const fields = { product_type: 'ブーケ', receive_date: { value_text: '未定', status: 'undecided' }, fulfillment_method: '店頭受取', quantity: '3', budget: '3000円（合計）', budget_scope: 'total', color_vibe: 'おまかせ' };
result = planConversation({ text: 'ありがとうございます', fields, sourceTimestamp });
assert.equal(result.questions.length, 0);
assert.equal(result.requiresOwner, true);
assert.equal(result.approvalRequired, true);
result = planConversation({ text: '明日配達でブーケをお願いしたい', sourceTimestamp });
assert.ok(result.ownerReasons.includes('urgent_capacity'));
assert.ok(result.ownerReasons.includes('delivery_feasibility'));
assert.equal(result.questions[0].key, 'delivery_area');
assert.ok(!result.questions.some(item => item.key === 'budget'));
assert.ok(result.questions.length <= 2);
result = planConversation({ text: 'まだ考え中です', lastQuestions: [{ key: 'receive_date' }, { key: 'product_type' }], sourceTimestamp });
assert.ok(!result.questions.some(item => ['receive_date', 'product_type'].includes(item.key)));
result = extractConversationFacts({ text: '未定です', lastQuestions: [{ key: 'receive_date' }], sourceTimestamp });
assert.equal(field(result, 'receive_date'), '未定');
result = planConversation({ text: '3つで2400円', fields: { product_type: 'ブーケ', receive_date: '2026-10-10', fulfillment_method: '店頭受取' }, sourceTimestamp });
assert.ok(result.questions.some(item => item.key === 'budget_scope'));
assert.equal(field(extract('スタンド花を1台、お願いします'), 'quantity'), '1');
assert.equal(field(extract('数量：１台'), 'quantity'), '1');
assert.equal(field(extract('数量：未定'), 'quantity'), undefined);
assert.equal(field(extract('ヘリウムを5本お願いします'), 'quantity'), '5');
assert.equal(field(extract('1台あたり15000円です'), 'quantity'), undefined);
result = extractConversationFacts({ text: 'おまかせで大丈夫です', lastQuestions: [{key:'budget_scope'}, {key:'color_vibe'}], sourceTimestamp });
assert.equal(field(result, 'color_vibe'), 'おまかせ');
assert.equal(field(extract('色はおまかせでお願いします'), 'color_vibe'), 'おまかせ');
assert.equal(field(extract('ラッピングはおまかせです'), 'color_vibe'), undefined);
assert.equal(field(extract('色はおまかせではなく選びたいです'), 'color_vibe'), undefined);
result = extractConversationFacts({ text: '合計です', lastQuestions: [{key:'budget_scope'}, {key:'color_vibe'}], sourceTimestamp });
assert.equal(field(result, 'budget_scope'), 'total');
result = planConversation({ text: 'ありがとうございます', fields: {...fields, color_vibe:undefined}, history:[{questions:[{key:'color_vibe'}]}], sourceTimestamp });
assert.equal(result.questions[0].key, 'color_vibe');
result = planConversation({ text: 'ありがとうございます', fields: {...fields, color_vibe:undefined}, lastQuestions:[{key:'color_vibe'}], sourceTimestamp });
assert.equal(result.questions[0].key, 'color_vibe');
assert.ok(!result.ownerReasons.includes('review_collected_details'));
console.log('Conversation planner: all scenario checks passed.');
